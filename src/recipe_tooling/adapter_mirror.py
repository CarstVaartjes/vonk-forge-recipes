"""Author and heal the adapter-source mirror: a release whose assets are named by SHA-256.

``add`` is the author-side ingress: it hashes each local file once, uploads it as
asset ``<sha256>`` when the mirror lacks it, and only then writes the manifest
entry, so no entry ever points at a missing asset. Assets are never replaced or
deleted. ``reconcile`` (run on main) re-uploads any declared blob the mirror lost
from its ``origin``, verified at ingress like every download; it only reports
what it cannot heal, so it never blocks a publication.
"""

from __future__ import annotations

import hashlib
import json
import os
import re
import shutil
import subprocess
import tempfile
import time
from collections.abc import Callable
from pathlib import Path

from recipe_tooling.adapter_sources import (
    CHUNK_BYTES,
    MANIFEST,
    ROOT,
    AdapterSource,
    AdapterSourceError,
    AdapterSources,
    Opener,
    _holds,
    default_cache,
    fetch,
    load,
    open_url,
)

Gh = Callable[[list[str]], str]
UPLOAD_ROUNDS = 3
GH_TIMEOUT_SECONDS = 300
_MIRROR = re.compile(
    r"^https://github\.com/(?P<repo>[^/]+/[^/]+)/releases/download/(?P<tag>[^/]+)/$"
)


def run_gh(arguments: list[str]) -> str:
    try:
        return subprocess.run(
            ["gh", *arguments],
            check=True,
            capture_output=True,
            text=True,
            timeout=GH_TIMEOUT_SECONDS,
        ).stdout
    except subprocess.CalledProcessError as error:
        raise AdapterSourceError(
            f"gh {arguments[:2]}: {error.stderr.strip()}"
        ) from error
    except (OSError, subprocess.TimeoutExpired) as error:
        raise AdapterSourceError(f"gh {arguments[:2]}: {error}") from error


def _release(sources: AdapterSources) -> tuple[str, str]:
    found = _MIRROR.match(sources.mirror)
    if found is None:
        raise AdapterSourceError(
            f"mirror is not a GitHub release URL: {sources.mirror}"
        )
    return found["repo"], found["tag"]


def _assets(sources: AdapterSources, gh: Gh) -> dict[str, dict[str, str | None]]:
    """Asset name to its GitHub-reported ``digest`` and upload ``state``."""
    repo, tag = _release(sources)
    listing = gh(["release", "view", tag, "--repo", repo, "--json", "assets"])
    return {
        asset["name"]: {"digest": asset.get("digest"), "state": asset.get("state")}
        for asset in json.loads(listing)["assets"]
    }


def _present(assets: dict[str, dict[str, str | None]], sha256: str) -> bool:
    """An asset counts only when fully uploaded and its digest is its name."""
    asset = assets.get(sha256)
    return (
        asset is not None
        and asset["state"] == "uploaded"
        and asset["digest"] == f"sha256:{sha256}"
    )


def _tampered(assets: dict[str, dict[str, str | None]], names: list[str]) -> list[str]:
    """Named assets whose reported digest is not their name: refused, never replaced."""
    return [
        f"mirror asset {name} reports {assets[name]['digest']}"
        for name in names
        if name in assets and assets[name]["digest"] not in (None, f"sha256:{name}")
    ]


def _upload(sources: AdapterSources, gh: Gh, sha256: str, blob: Path) -> str:
    """Upload the verified blob (a file named by its digest); return "" or the evidence."""
    repo, tag = _release(sources)
    last = ""
    for _ in range(UPLOAD_ROUNDS):
        try:
            gh(["release", "upload", tag, str(blob), "--repo", repo])
            return ""
        except AdapterSourceError as error:
            last = str(error)
            try:
                if _present(_assets(sources, gh), sha256):  # a concurrent run won
                    return ""
            except (AdapterSourceError, ValueError, KeyError) as relist:
                last = f"{last}; relist: {relist}"
    return f"upload of {sha256} failed: {last}"


def _hash(path: Path) -> tuple[str, int]:
    digest = hashlib.sha256()
    size = 0
    with path.open("rb") as handle:
        while chunk := handle.read(CHUNK_BYTES):
            digest.update(chunk)
            size += len(chunk)
    return digest.hexdigest(), size


IGNORE_BEGIN = "# adapter-sources: declared paths (generated by tools/adapter-sources)"
IGNORE_END = "# adapter-sources: end"


def _ignore_line(path: str) -> str:
    return "/" + re.sub(r"([\\\[\]*?!# ])", r"\\\1", path)


def _write(root: Path, sources: AdapterSources) -> None:
    """Write the manifest and the ignore block that keeps its paths out of commits."""
    document = sources.model_dump(mode="json", exclude_none=True)
    document["sources"] = dict(sorted(document["sources"].items()))
    (root / MANIFEST).write_text(json.dumps(document, indent=2) + "\n")
    paths = sorted(p for source in sources.sources.values() for p in source.paths)
    ignore = root / ".gitignore"
    text = ignore.read_text() if ignore.is_file() else ""
    begin = text.find(IGNORE_BEGIN)
    end = text.find(IGNORE_END)
    if begin != -1 and end > begin:
        text = text[:begin] + text[end + len(IGNORE_END) :].lstrip("\n")
    text = text.rstrip("\n")
    if paths:
        block = "\n".join([IGNORE_BEGIN, *map(_ignore_line, paths), IGNORE_END])
        text = f"{text}\n\n{block}" if text else block
    ignore.write_text(text + "\n" if text else "")


def undeclare(paths: list[str], *, root: Path = ROOT) -> None:
    """Drop paths from the manifest (a superseded file); the mirror keeps the blob."""
    sources = load(root)
    gone = set(paths)
    kept = {}
    for key, source in sources.sources.items():
        remaining = tuple(p for p in source.paths if p not in gone)
        if remaining:
            kept[key] = source.model_copy(update={"paths": remaining})
    if kept != sources.sources:
        _write(root, AdapterSources(mirror=sources.mirror, sources=kept))


def add(
    paths: list[str],
    *,
    root: Path = ROOT,
    origin: str | None = None,
    also: tuple[str, ...] = (),
    cache: Path | None = None,
    gh: Gh = run_gh,
) -> list[str]:
    """Mirror each file, then declare it; return the digests that were uploaded.

    ``also`` declares further paths for the one blob the files hold, without needing
    them on disk (a vendor file the tree materializes from the mirror).
    """
    sources = load(root)
    cache = default_cache() if cache is None else cache
    found: dict[str, tuple[int, list[str]]] = {}
    for path in paths:
        resolved = (root / path).resolve()
        relative = resolved.relative_to(root.resolve()).as_posix()
        sha256, size = _hash(resolved)
        found.setdefault(sha256, (size, []))[1].append(relative)
        if not _holds(cache / sha256, size):
            cache.mkdir(parents=True, exist_ok=True)
            descriptor, temporary = tempfile.mkstemp(dir=cache, prefix=f".{sha256}.")
            try:
                with (
                    os.fdopen(descriptor, "wb") as output,
                    resolved.open("rb") as source,
                ):
                    shutil.copyfileobj(source, output)
                Path(temporary).replace(cache / sha256)
            finally:
                Path(temporary).unlink(missing_ok=True)
    if (origin is not None or also) and len(found) != 1:
        raise AdapterSourceError(
            "--origin and also name one blob, but the files differ"
        )
    for held in found.values():
        held[1].extend(p for p in also if p not in held[1])
    assets = _assets(sources, gh)
    if bad := _tampered(assets, list(found)):
        raise AdapterSourceError("; ".join(bad))
    uploaded = []
    for sha256 in found:
        if not _present(assets, sha256):
            if failure := _upload(sources, gh, sha256, cache / sha256):
                raise AdapterSourceError(failure)
            uploaded.append(sha256)
    # Every asset exists now, so the entries may be written. A path moves to the
    # newest digest declared for it.
    declared = {key: value.model_dump() for key, value in sources.sources.items()}
    for sha256, (size, held) in found.items():
        for entry in declared.values():
            entry["paths"] = tuple(p for p in entry["paths"] if p not in held)
        entry = declared.setdefault(
            sha256, {"size_bytes": size, "origin": None, "paths": []}
        )
        entry["origin"] = origin or entry["origin"]
        entry["paths"] = tuple(sorted({*entry["paths"], *held}))
    merged = {
        key: AdapterSource.model_validate(entry)
        for key, entry in declared.items()
        if entry["paths"]
    }
    _write(root, AdapterSources(mirror=sources.mirror, sources=merged))
    return uploaded


def reconcile(
    root: Path = ROOT,
    *,
    cache: Path | None = None,
    opener: Opener = open_url,
    sleep: Callable[[float], None] = time.sleep,
    gh: Gh = run_gh,
) -> list[str]:
    """Re-upload declared blobs the mirror lacks; return what could not be healed."""
    sources = load(root)
    cache = default_cache() if cache is None else cache
    try:
        assets = _assets(sources, gh)
    except (AdapterSourceError, ValueError, KeyError) as error:
        return [f"mirror listing unavailable: {error}"]
    problems = _tampered(assets, list(sources.sources))
    # sequential: healing is rare (only blobs the mirror lost) and each step is one upload
    for sha256, source in sources.sources.items():
        if _present(assets, sha256):
            continue
        blob = cache / sha256
        if not _holds(blob, source.size_bytes):
            if source.origin is None:
                problems.append(
                    f"sha256:{sha256} is not in the mirror and has no origin"
                )
                continue
            cache.mkdir(parents=True, exist_ok=True)
            failure = fetch(
                sources, sha256, cache, opener, sleep, urls=(source.origin,)
            )
            if failure:
                problems.append(failure)
                continue
        if failure := _upload(sources, gh, sha256, blob):
            problems.append(failure)
    return problems
