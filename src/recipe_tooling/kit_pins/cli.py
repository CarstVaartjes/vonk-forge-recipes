"""Derive and check the pins a creator's kit declares (``kit-lock.json``).

A recipe built from a creator's kit (a patch stack, launch scripts, a configuration that
names the base engine version, the model it serves, the image it runs on) pins only the
kit: ``provenance.source_reference``. What the kit builds on is the kit's own statement
at that commit, so this repository does not author a second pin for it. The adapter's
``vendored-upstream.json`` says *where* the kit declares each dependency, in the shape of
a Renovate regex manager::

    "kit": {
      "dependencies": {
        "base": {
          "datasource": "git-ref",
          "repo": "ashhart/TensorFold",
          "file": "scripts/config.sh",
          "pattern": "^TF_VERSION=\"\\$\\{TF_VERSION:-(?P<version>[^}\"]+)\\}\"",
          "override": {"ref": "v0.6.1", "reason": "why this recipe deviates"}
        },
        "model": {
          "datasource": "hf-revision",
          "file": "scripts/config.sh",
          "pattern": "^\\s*(?P<repo>[\\w.-]+/[\\w.-]+)\\) _rev=(?P<version>[0-9a-f]{40}) ;;",
          "binds": "primary"
        }
      }
    }

* ``file`` and ``pattern`` locate the declared value (the named group ``version``) in the
  kit at the pinned commit; exactly one distinct value is required.
* ``datasource`` says what the value names, and is resolved to an immutable value once,
  here, never at build time:

  - ``git-ref``: a tag, branch or commit of a GitHub repository, locked as its commit. A
    declared *branch* is followed like a Nix branch input (``"kind": "branch"``): ``lock``
    resolves the head once; the build and ``check`` use only the locked commit, and the
    refresh scanner reports a moved head as a change of the kit's dependency (a review).
  - ``hf-revision``: a revision (a commit, or a branch or tag) of a Hugging Face model
    repository, locked as its commit. ``binds`` names the recipe model (``models[].id``)
    the kit's pin is for: that model's catalogued document must be this repository at this
    revision, so a model that is not the kit's is rejected. Resolving needs the revision
    to be anonymously readable.
  - ``oci-image``: a tag (or ``sha256:`` digest) of a container image repository, locked as
    the digest of its ``linux/arm64`` manifest (an index is followed to that entry; the
    platform builds and runs on arm64 only). The Dockerfile's ``FROM`` lines of that
    repository and the recipe's ``execution.build.base_image`` must carry the locked digest.
* ``repo`` names the repository the value is of. A kit that also declares *which*
  repository (a fork, a model id, an image) gives either ``repo_pattern`` (a regex with a
  ``(?P<repo>...)`` group, exactly one distinct match in the same file) instead of
  ``repo``, or a ``repo`` group in ``pattern`` itself when one line pairs the two (a shell
  ``case`` on the model id). The lock records the repository with the value, and a kit
  that moves to another repository is a review like a moved ref.
* ``override`` is the only way to deviate from the kit (a known-bad upstream, a security
  fix). It needs a reason, replaces the declaration (``ref``, ``revision`` or ``digest``,
  and ``repo`` when it is another repository); refresh reports it as overridden and
  proposes nothing.

``kit-lock.json`` is the derived, committed result::

    {"kit": {"repo": ..., "commit": ...},
     "dependencies": {"base": {"datasource": "git-ref", "repo": ..., "ref": ..., "kind": ...,
                               "commit": ...},
                      "model": {"datasource": "hf-revision", "repo": ..., "ref": ...,
                                "kind": ..., "revision": ...},
                      "image": {"datasource": "oci-image", "repo": ..., "ref": ..., "kind": ...,
                                "digest": ...}}}

``kind`` says what ``ref`` named when it was locked: ``tag``, ``branch`` or ``commit``
(``digest`` for an image declared by digest).

It is generated by ``tools/kit-pins lock`` and never edited by hand. ``tools/kit-pins
check`` is the "lock is up to date" gate: it re-derives the lock from the kit commit the
recipe pins (one fetch of that exact commit's declaring file; the locked values are not
looked up again) and fails when the committed lock differs, when the adapter keeps a second
hand-authored pin beside a declaration, or when what consumes a pin does not follow the
lock: the Dockerfile's labels and the vendored archive for a ``git-ref`` base, the bound
Model for an ``hf-revision``, the Dockerfile and ``base_image`` for an ``oci-image``.

A recipe may cite its kit with a ``blob`` URL of the declaring file (a playbook's README) as
well as a ``tree`` URL. A kit that is one directory of a creator's monorepo, of which the
recipe uses only the declared values, sets ``"whole": false`` on the ``kit`` block: the
refresh scanner then checks the declarations and judges the repository's other changes as it
does for any source (files the adapter names by URL and patches), not every changed file.

A kit that provides a prebuilt image is run as published, never rebuilt (owner rule): the
recipe's Dockerfile builds ``FROM`` that image, pinned by digest, and at most adds a thin
layer. ``tools/kit-pins check`` therefore also scans every kit a recipe cites, at the pinned
commit, for the container images it runs or pulls (Dockerfile ``FROM``/``ARG`` image
defaults, ``IMG=``/``IMAGE=`` assignments, ``docker run|pull|create``, compose ``image:``;
documentation, tests, evidence and CI files are not scanned, a README only for its
``docker run|pull`` lines; Docker Hub / GHCR / Quay references of engines and bases such as
``vllm/vllm-openai``, ``lmsysorg/sglang`` or ``nvcr.io/*`` are not creator images). Each
creator image the kit references must be one the recipe's Dockerfile builds ``FROM``, or be
recorded for that recipe in ``policy/kit-image-exceptions.json`` with a reason::

    {"<recipe id>": {"ghcr.io/owner/name": "why the recipe does not run it"}}

``tools/kit-pins images [<recipe>...]`` prints what the scan finds.

``tools/kit-pins lock <recipe>`` also moves the consumers: it fetches the base archive for
the locked commit, mirrors it and declares it in ``adapter-sources.json`` (origin: the
codeload URL; a failed upload removes the file, and a rerun fetches and declares it
again), and moves the Dockerfile's commit, archive file name and archive digest; it rebinds the recipe to the catalogued Model of the locked revision (the Model
must be catalogued first, with ``tools/catalog-hf-model``); it moves the image digest in the
Dockerfile and the recipe. Prose in the Dockerfile (a header comment, licence labels) is
the author's to review.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path
from typing import Any

from recipe_tooling.adapter_sources import materialize_or_exit
from recipe_tooling.kit_pins.check import check_images, check_recipe
from recipe_tooling.kit_pins.image_scan import dockerfile_images, kit_images, kit_scope
from recipe_tooling.kit_pins.lock import adapter_of, kit_of, manifest_of
from recipe_tooling.kit_pins.model import MANIFEST, KitError
from recipe_tooling.kit_pins.sources import cli_source
from recipe_tooling.kit_pins.upstream import Upstream
from recipe_tooling.kit_pins.write import apply_lock
from recipe_tooling.paths import REPO_ROOT

ROOT = REPO_ROOT

# ---------------------------------------------------------------------------
# Command line
# ---------------------------------------------------------------------------


def load_recipes(root: Path) -> dict[str, dict[str, Any]]:
    return {
        json.loads(p.read_text(encoding="utf-8"))["identity"]["slug"]: json.loads(
            p.read_text(encoding="utf-8")
        )
        for p in sorted((root / "recipes").glob("*.json"))
    }


def kit_recipes(root: Path, recipes: dict[str, dict[str, Any]]) -> list[str]:
    found = []
    for recipe_id, recipe in recipes.items():
        adapter = adapter_of(root, recipe)
        if (
            adapter is not None
            and (adapter / MANIFEST).is_file()
            and "kit" in manifest_of(adapter)
        ):
            found.append(recipe_id)
    return found


def print_images(recipes: dict[str, dict[str, Any]], names: list[str]) -> int:
    source = cli_source()
    for recipe_id in names or sorted(recipes):
        kit = kit_of(recipes[recipe_id])
        if kit is None:
            continue
        used = dockerfile_images(
            adapter_of(ROOT, recipes[recipe_id]) or ROOT, recipes[recipe_id]
        )
        for found in kit_images(source, *kit, kit_scope(recipes[recipe_id])):
            state = "runs" if found["repo"] in used else "does not run"
            print(
                f"{recipe_id}\t{state}\t{found['reference']}\t{found['file']}:{found['line']}"
            )
    return 0


def process(
    command: str, recipe_id: str, recipe: dict[str, Any], source: Upstream
) -> int:
    """Lock or check one recipe; the number of problems printed (a busy provider counts)."""
    try:
        if command == "lock":
            moved = apply_lock(ROOT, recipe_id, recipe, source)
            print(f"{recipe_id}: " + ("; ".join(moved) if moved else "lock is current"))
            return 0
        problems = check_recipe(ROOT, recipe_id, recipe, source)
    except (KitError, RuntimeError) as error:  # incl. UpstreamBusy: next recipe goes on
        problems = [f"{recipe_id}: {error}"]
    for problem in problems:
        print(problem, file=sys.stderr)
    return len(problems)


def main(argv: list[str]) -> int:
    if not argv or argv[0] not in {"lock", "check", "images"}:
        print(__doc__)
        return 2
    command, names = argv[0], argv[1:]
    recipes = load_recipes(ROOT)
    if command == "images":
        return print_images(recipes, names)

    materialize_or_exit(ROOT)  # lock and check read the vendored base archives
    targets = kit_recipes(ROOT, recipes)
    if names and names != ["--all"]:
        unknown = [n for n in names if n not in recipes]
        if unknown:
            print(f"unknown recipe: {', '.join(unknown)}", file=sys.stderr)
            return 2
        targets = names
    elif command == "lock" and names != ["--all"]:
        print("name the recipe(s) to lock, or --all", file=sys.stderr)
        return 2
    source = cli_source()
    failed = sum(
        process(command, recipe_id, recipes[recipe_id], source) for recipe_id in targets
    )
    if command == "check":
        if not names or names == ["--all"]:
            for problem in check_images(
                ROOT,
                recipes,
                source,
                notice=lambda message: print(f"notice: {message}", file=sys.stderr),
            ):
                print(problem, file=sys.stderr)
                failed += 1
        if failed:
            print(f"{failed} kit lock problem(s)", file=sys.stderr)
            return 1
        print(f"Kit locks are current ({len(targets)} recipes with a kit declaration)")
    return 1 if failed else 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
